"""Data Contracts for EarthMind Stage R9 Query Processing.

Defines Pydantic models for:
- QueryProcessingStatus: Execution status enum for R9 pipeline operations
- QueryClassification: Extensible enum for categorizing query intent/topic
- StructuredQueryFilter: Representation of individual filter conditions
- AgriculturalMetadata: Domain-specific agricultural fields extracted without hallucination
- QueryMetadata: Combined classification, agricultural metadata, language, and confidence
- QueryExpansion: Individual query expansion or reformulation variant
- DenseQuery: Query representation for R5 Dense Vector Retrieval
- SparseQuery: Query representation for R6 Sparse Vector / Lexical Retrieval
- RetrievalQuery: Final unified retrieval query container bridging to R5/R6 via R7
- QueryProcessingRequest: Incoming user/system query processing request
- QueryProcessingResponse: Final R9 response payload containing RetrievalQuery and trace logs
"""

from enum import Enum
import time
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from pydantic import BaseModel, Field

if TYPE_CHECKING:
    from core.schemas.hybrid import HybridRetrievalRequest


class QueryProcessingStatus(str, Enum):
    """Execution status for R9 query processing operation."""
    SUCCESS = "SUCCESS"
    PARTIAL = "PARTIAL"
    INVALID = "INVALID"
    FAILED = "FAILED"
    TIMEOUT = "TIMEOUT"
    UNAVAILABLE = "UNAVAILABLE"


class QueryClassification(str, Enum):
    """Broad categorization of query intent and functional focus."""
    INFORMATION_LOOKUP = "INFORMATION_LOOKUP"
    DIAGNOSIS_RELATED = "DIAGNOSIS_RELATED"
    CROP_QUERY = "CROP_QUERY"
    SOIL_QUERY = "SOIL_QUERY"
    WEATHER_RELATED = "WEATHER_RELATED"
    PEST_DISEASE_RELATED = "PEST_DISEASE_RELATED"
    FARM_PRACTICE = "FARM_PRACTICE"
    AGRICULTURAL_GUIDANCE = "AGRICULTURAL_GUIDANCE"
    GENERAL_AGRICULTURE = "GENERAL_AGRICULTURE"
    UNKNOWN = "UNKNOWN"


class StructuredQueryFilter(BaseModel):
    """Structured key-value condition for backend metadata filtering."""
    field: str = Field(..., description="Target metadata attribute name")
    operator: str = Field("eq", description="Comparison operator (eq, ne, in, range, gt, lt)")
    value: Any = Field(..., description="Value or range tuple to filter on")


class AgriculturalMetadata(BaseModel):
    """
    Extracted domain-specific agricultural attributes.
    Attributes must only be populated when explicitly supported by query text or upstream context.
    Uncertain or unmentioned fields remain None.
    """
    crop: Optional[str] = Field(None, description="Crop name (e.g., wheat, rice, cotton)")
    crop_stage: Optional[str] = Field(None, description="Growth stage (e.g., vegetative, flowering, harvest)")
    disease_pest: Optional[str] = Field(None, description="Pathogen or pest name (e.g., yellow rust, aphid)")
    soil_type: Optional[str] = Field(None, description="Soil classification (e.g., black cotton, alluvial)")
    soil_condition: Optional[str] = Field(None, description="Soil condition (e.g., alkaline, acidic, saline)")
    region: Optional[str] = Field(None, description="Geographic region, state, or district")
    state: Optional[str] = Field(None, description="State identifier")
    district: Optional[str] = Field(None, description="District identifier")
    season: Optional[str] = Field(None, description="Agri season (e.g., Kharif, Rabi, Zaid)")
    farming_practice: Optional[str] = Field(None, description="Method (e.g., organic, drip irrigation, zero tillage)")
    topic: Optional[str] = Field(None, description="General subject area (e.g., fertilizer dosage, seed rate)")
    time_range: Optional[str] = Field(None, description="Temporal constraint if explicitly mentioned")


class QueryMetadata(BaseModel):
    """Combined metadata enrichment produced during R9 query processing."""
    classification: QueryClassification = Field(QueryClassification.UNKNOWN, description="Query classification category")
    agricultural_metadata: AgriculturalMetadata = Field(default_factory=AgriculturalMetadata, description="Extracted agricultural fields")
    language: str = Field("en", description="ISO language code of normalized query")
    confidence: float = Field(1.0, ge=0.0, le=1.0, description="Overall extraction and classification confidence")
    intent_attributes: Dict[str, Any] = Field(default_factory=dict, description="Additional intent metadata")
    additional_metadata: Dict[str, Any] = Field(default_factory=dict, description="Administrative/system metadata")


class QueryExpansion(BaseModel):
    """Individual expanded query variant or term generated by reformulation strategy."""
    expanded_text: str = Field(..., description="Expanded query phrase or term string")
    expansion_type: str = Field("SYNONYM", description="Type of expansion (SYNONYM, TRANSLITERATION, DOMAIN_VARIANT, REFORMULATION)")
    weight: float = Field(1.0, ge=0.0, le=2.0, description="Importance weight assigned to this expansion")
    target_language: Optional[str] = Field(None, description="Language code of expanded text")
    source_term: Optional[str] = Field(None, description="Source term in original query that triggered expansion")


class DenseQuery(BaseModel):
    """Query payload prepared for R5 Dense Vector Retrieval."""
    dense_query_text: str = Field(..., description="Text payload sent to embedding provider")
    dense_vector: Optional[List[float]] = Field(None, description="Optional pre-computed dense vector embedding")
    top_k: int = Field(20, description="Requested top-k candidates from dense branch")
    embedding_model_hint: Optional[str] = Field(None, description="Suggested embedding model identifier")


class SparseQuery(BaseModel):
    """Query payload prepared for R6 Sparse / Lexical Retrieval."""
    sparse_query_text: str = Field(..., description="Text payload sent to sparse provider")
    lexical_terms: List[str] = Field(default_factory=list, description="Extracted normalized lexical tokens")
    expanded_terms: List[str] = Field(default_factory=list, description="Expanded lexical terms")
    term_weights: Dict[str, float] = Field(default_factory=dict, description="Weight per lexical term")
    sparse_indices: Optional[List[int]] = Field(None, description="Optional pre-computed sparse feature indices")
    sparse_values: Optional[List[float]] = Field(None, description="Optional pre-computed sparse feature weights")


class RetrievalQuery(BaseModel):
    """
    Final output container from Stage R9 Query Processing.
    Directly consumable by downstream retrieval interfaces (R5/R6/R7).
    """
    original_query: str = Field(..., description="Verbatim original input query string")
    normalized_query: str = Field(..., description="Normalized, cleaned query string")
    expanded_queries: List[QueryExpansion] = Field(default_factory=list, description="Generated query expansions")
    dense_query: DenseQuery = Field(..., description="Dense retrieval representation for R5")
    sparse_query: SparseQuery = Field(..., description="Sparse retrieval representation for R6")
    structured_filters: List[StructuredQueryFilter] = Field(default_factory=list, description="Generic filter specifications")
    metadata: QueryMetadata = Field(default_factory=QueryMetadata, description="Extracted query metadata")
    top_k: int = Field(10, description="Final fused candidates limit requested")
    dense_top_k: int = Field(20, description="Dense branch candidate limit")
    sparse_top_k: int = Field(20, description="Sparse branch candidate limit")
    collection_name: str = Field("earthmind_knowledge", description="Target knowledge collection name")
    provenance: Dict[str, Any] = Field(default_factory=dict, description="Query processing lineage and settings trace")
    request_id: Optional[str] = Field(None, description="Correlation / request tracing ID")

    def to_hybrid_retrieval_request(
        self,
        fusion_strategy: str = "RRF",
        rrf_k: int = 60,
        enable_dense: bool = True,
        enable_sparse: bool = True,
        timeout: float = 10.0,
    ) -> "HybridRetrievalRequest":
        """
        Bridge method converting a RetrievalQuery into Stage R7 HybridRetrievalRequest.
        Translates provider-independent structured filters into a dictionary format.
        """
        from core.schemas.hybrid import HybridRetrievalRequest

        filter_dict: Dict[str, Any] = {}
        for f in self.structured_filters:
            filter_dict[f.field] = f.value

        return HybridRetrievalRequest(
            query_text=self.normalized_query,
            dense_vector=self.dense_query.dense_vector,
            sparse_indices=self.sparse_query.sparse_indices,
            sparse_values=self.sparse_query.sparse_values,
            collection_name=self.collection_name,
            top_k=self.top_k,
            dense_top_k=self.dense_top_k,
            sparse_top_k=self.sparse_top_k,
            filters=filter_dict if filter_dict else None,
            fusion_strategy=fusion_strategy,
            rrf_k=rrf_k,
            enable_dense=enable_dense,
            enable_sparse=enable_sparse,
            timeout=timeout,
            request_id=self.request_id,
        )


class QueryProcessingRequest(BaseModel):
    """Incoming request for Stage R9 Query Processing."""
    query_text: str = Field(..., description="Raw user or system input query string")
    request_id: Optional[str] = Field(None, description="Correlation / request tracing ID")
    language: Optional[str] = Field(None, description="ISO language code hint (e.g. 'hi', 'en')")
    region: Optional[str] = Field(None, description="Geographic region context")
    user_context: Dict[str, Any] = Field(default_factory=dict, description="Upstream user/farm context")
    filters: Optional[Dict[str, Any]] = Field(None, description="Explicit caller-provided metadata filters")
    top_k: int = Field(10, description="Target top-k candidates")
    dense_top_k: int = Field(20, description="Target dense branch top-k")
    sparse_top_k: int = Field(20, description="Target sparse branch top-k")
    collection_name: str = Field("earthmind_knowledge", description="Target collection name")
    timeout: float = Field(10.0, description="Execution timeout in seconds")
    enable_expansion: bool = Field(True, description="Whether to apply query expansion/reformulation")
    max_expansions: int = Field(3, description="Maximum number of query expansions to generate")


class QueryProcessingResponse(BaseModel):
    """Output payload from Stage R9 Query Processing."""
    request_id: Optional[str] = Field(None, description="Correlation / request tracing ID")
    status: QueryProcessingStatus = Field(QueryProcessingStatus.SUCCESS, description="Processing status")
    original_query: str = Field(..., description="Original input query string")
    retrieval_query: Optional[RetrievalQuery] = Field(None, description="Built retrieval query structure")
    processing_time_ms: float = Field(0.0, description="Pipeline latency in milliseconds")
    warnings: List[str] = Field(default_factory=list, description="Operational warnings or partial failures")
    error_message: Optional[str] = Field(None, description="Error details if status is FAILED or INVALID")
    trace_steps: List[Dict[str, Any]] = Field(default_factory=list, description="Step-by-step processing audit trail")
