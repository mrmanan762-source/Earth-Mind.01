"""Stage R15 Quality & Performance Evaluation Data Contracts & Schemas."""

import uuid
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class QualityStatus(str, Enum):
    """Explicit status codes for quality measurements and metrics."""
    EVALUATED = "EVALUATED"
    NOT_EVALUABLE = "NOT_EVALUABLE"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    UNAVAILABLE = "UNAVAILABLE"
    FAILED = "FAILED"
    PARTIAL = "PARTIAL"


class ReliabilityStatus(str, Enum):
    """Execution and reliability classification for evaluation cases."""
    SUCCESS = "SUCCESS"
    VALID_EMPTY_RESULT = "VALID_EMPTY_RESULT"
    SYSTEM_FAILURE = "SYSTEM_FAILURE"
    PARTIAL_RESULT = "PARTIAL_RESULT"
    TIMEOUT = "TIMEOUT"
    UNAVAILABLE = "UNAVAILABLE"


class EvaluationCase(BaseModel):
    """Single query evaluation test case with optional ground-truth judgments."""

    case_id: str = Field(default_factory=lambda: f"case_{uuid.uuid4().hex[:8]}", description="Unique case identifier")
    query_text: str = Field(..., description="Verbatim input query text")
    language: str = Field("hi", description="ISO language code (e.g., 'en', 'hi', 'mr')")
    domain_category: str = Field("general_agriculture", description="Agricultural domain category (e.g. crop_disease, soil, pests)")
    expected_relevant_evidence_ids: List[str] = Field(default_factory=list, description="IDs of ground-truth evidence items")
    expected_relevant_chunk_ids: List[str] = Field(default_factory=list, description="IDs of ground-truth knowledge chunks")
    expected_relevant_doc_ids: List[str] = Field(default_factory=list, description="IDs of ground-truth documents")
    relevance_judgments: Dict[str, float] = Field(default_factory=dict, description="Graded relevance map {id: score}")
    expected_source_types: List[str] = Field(default_factory=list, description="Expected source types (KNOWLEDGE_BASE, WEB_SEARCH)")
    reference_answer: Optional[str] = Field(None, description="Optional reference answer or criteria")
    difficulty: str = Field("medium", description="Case difficulty (easy, medium, hard, edge_case)")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary case metadata")
    version: str = Field("1.0.0", description="Case schema/version tag")


class EvaluationDataset(BaseModel):
    """Collection of evaluation cases for benchmark runs."""

    dataset_id: str = Field(default_factory=lambda: f"ds_{uuid.uuid4().hex[:8]}", description="Unique dataset identifier")
    name: str = Field(..., description="Dataset title")
    version: str = Field("1.0.0", description="Dataset semantic version")
    description: str = Field("", description="Dataset description")
    cases: List[EvaluationCase] = Field(default_factory=list, description="List of evaluation cases")
    created_at: str = Field(..., description="ISO 8601 creation timestamp")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Dataset metadata")


class EvaluationMeasurement(BaseModel):
    """Detailed telemetry and metric measurements for a single evaluation case run."""

    measurement_id: str = Field(default_factory=lambda: f"meas_{uuid.uuid4().hex[:8]}", description="Unique measurement ID")
    case_id: str = Field(..., description="Associated EvaluationCase ID")
    request_id: str = Field(..., description="Pipeline request ID")
    trace_id: str = Field(..., description="Pipeline trace ID")
    status: ReliabilityStatus = Field(ReliabilityStatus.SUCCESS, description="Execution status")
    error_code: Optional[str] = Field(None, description="Error code if failed")
    error_message: Optional[str] = Field(None, description="Error message if failed")
    stage_latencies_ms: Dict[str, float] = Field(default_factory=dict, description="Per-stage latencies in ms")
    total_latency_ms: float = Field(0.0, description="Total latency in ms")
    retrieved_chunk_ids: List[str] = Field(default_factory=list, description="Chunk IDs retrieved by R7")
    reranked_chunk_ids: List[str] = Field(default_factory=list, description="Chunk IDs returned after R8 reranking")
    evidence_ids: List[str] = Field(default_factory=list, description="Evidence item IDs generated by R11")
    validation_status: str = Field("VALID", description="R12 validation status")
    context_item_count: int = Field(0, description="Number of B2 ContextItems produced")
    resource_usage: Dict[str, Any] = Field(default_factory=dict, description="CPU, Memory, Qdrant usage indicators")


class QualityMetrics(BaseModel):
    """Calculated retrieval, reranking, evidence, and end-to-end quality metrics."""

    precision_at_k: Dict[int, Optional[float]] = Field(default_factory=dict, description="Precision @ K")
    recall_at_k: Dict[int, Optional[float]] = Field(default_factory=dict, description="Recall @ K")
    hit_rate_at_k: Dict[int, Optional[float]] = Field(default_factory=dict, description="Hit Rate @ K")
    mrr: Optional[float] = Field(None, description="Mean Reciprocal Rank")
    ndcg_at_k: Dict[int, Optional[float]] = Field(default_factory=dict, description="Normalized Discounted Cumulative Gain @ K")
    rerank_movement: Dict[str, Any] = Field(default_factory=dict, description="Rank movement and score gain metrics")
    evidence_metrics: Dict[str, Any] = Field(default_factory=dict, description="Evidence completeness, lineage, and validation metrics")
    status: QualityStatus = Field(QualityStatus.EVALUATED, description="Quality evaluation status")
    status_reason: str = Field("", description="Reason if status is not EVALUATED")


class LatencySummary(BaseModel):
    """Statistical summary of latencies."""
    p50_ms: float = 0.0
    p90_ms: float = 0.0
    p95_ms: float = 0.0
    p99_ms: float = 0.0
    mean_ms: float = 0.0
    min_ms: float = 0.0
    max_ms: float = 0.0


class PerformanceMetrics(BaseModel):
    """Calculated latency, throughput, and resource utilization metrics."""

    total_latency: LatencySummary = Field(default_factory=LatencySummary, description="E2E latency statistics")
    stage_latencies: Dict[str, LatencySummary] = Field(default_factory=dict, description="Per-stage latency statistics")
    throughput_qps: float = Field(0.0, description="Queries per second")
    cases_per_second: float = Field(0.0, description="Cases processed per second")
    execution_mode: str = Field("sequential", description="Execution mode ('sequential' or 'concurrent')")
    resource_usage: Dict[str, Any] = Field(default_factory=dict, description="CPU, Memory (MB), Qdrant metrics")


class ReliabilityMetrics(BaseModel):
    """Calculated reliability, error rates, and failure classifications."""

    total_cases: int = Field(0, description="Total cases evaluated")
    success_count: int = Field(0, description="Successful evaluations")
    valid_empty_count: int = Field(0, description="Valid empty retrieval results")
    system_failure_count: int = Field(0, description="System error failures")
    partial_result_count: int = Field(0, description="Partial result counts")
    timeout_count: int = Field(0, description="Timed out runs")
    success_rate: float = Field(0.0, description="Success rate ratio (0.0 to 1.0)")
    failure_rate: float = Field(0.0, description="Failure rate ratio (0.0 to 1.0)")
    empty_result_rate: float = Field(0.0, description="Empty result rate ratio")
    failure_breakdown: Dict[str, int] = Field(default_factory=dict, description="Count per failure type")


class BaselineResult(BaseModel):
    """Comparative result summary for a controlled baseline scenario."""

    baseline_name: str = Field(..., description="Baseline identifier e.g. 'DENSE_ONLY', 'SPARSE_ONLY', 'HYBRID_NO_RERANK', 'FULL_HYBRID_RERANK'")
    configuration_snapshot: Dict[str, Any] = Field(default_factory=dict, description="Config settings for baseline")
    dataset_id: str = Field(..., description="Dataset evaluated against")
    quality_metrics: QualityMetrics = Field(..., description="Baseline quality metrics")
    performance_metrics: PerformanceMetrics = Field(..., description="Baseline performance metrics")
    reliability_metrics: ReliabilityMetrics = Field(..., description="Baseline reliability metrics")
    timestamp: str = Field(..., description="ISO timestamp of baseline run")


class RegressionResult(BaseModel):
    """Comparison metric result between two evaluation runs."""

    metric_name: str = Field(..., description="Metric key being compared")
    run_a_id: str = Field(..., description="Baseline/Previous run ID")
    run_b_id: str = Field(..., description="Current/Target run ID")
    value_a: Optional[float] = Field(None, description="Previous metric value")
    value_b: Optional[float] = Field(None, description="Current metric value")
    absolute_diff: Optional[float] = Field(None, description="value_b - value_a")
    relative_diff_pct: Optional[float] = Field(None, description="Percentage change")
    regression_detected: bool = Field(False, description="True if performance/quality degraded beyond tolerance")
    details: str = Field("", description="Detailed explanation")


class EvaluationRun(BaseModel):
    """Complete metadata, environment, and output record for an evaluation execution."""

    run_id: str = Field(default_factory=lambda: f"eval_run_{uuid.uuid4().hex[:8]}", description="Unique evaluation run ID")
    dataset_id: str = Field(..., description="EvaluationDataset ID used")
    dataset_version: str = Field("1.0.0", description="EvaluationDataset version")
    timestamp: str = Field(..., description="ISO start timestamp")
    knowledge_base_version: str = Field("R2_R3_v1.0", description="Target knowledge base/corpus version")
    embedding_model_version: str = Field("1.0.0", description="Embedding model version")
    sparse_version: str = Field("BM25_v1", description="Sparse index version")
    qdrant_version: str = Field("1.19.1", description="Vector index version")
    fusion_strategy_version: str = Field("R7_RRF_v1", description="Hybrid fusion version")
    reranker_version: str = Field("BAAI_bge_v1", description="Reranker version")
    query_processing_version: str = Field("R9_v1.0", description="Query processing version")
    model_runtime_version: str = Field("0.1.0", description="System runtime version")
    config_snapshot: Dict[str, Any] = Field(default_factory=dict, description="System configuration snapshot")
    environment_metadata: Dict[str, Any] = Field(default_factory=dict, description="Environment variables / OS details")
    measurements: List[EvaluationMeasurement] = Field(default_factory=list, description="Per-case measurements")
    quality_metrics: Optional[QualityMetrics] = Field(None, description="Aggregated quality metrics")
    performance_metrics: Optional[PerformanceMetrics] = Field(None, description="Aggregated performance metrics")
    reliability_metrics: Optional[ReliabilityMetrics] = Field(None, description="Aggregated reliability metrics")
    status: str = Field("COMPLETED", description="Overall run status")


class EvaluationReport(BaseModel):
    """Final comprehensive structured evaluation report."""

    report_id: str = Field(default_factory=lambda: f"rpt_{uuid.uuid4().hex[:8]}", description="Unique report ID")
    run_id: str = Field(..., description="Associated EvaluationRun ID")
    timestamp: str = Field(..., description="ISO generation timestamp")
    evaluation_metadata: Dict[str, Any] = Field(default_factory=dict, description="Run & reproducibility metadata")
    dataset_info: Dict[str, Any] = Field(default_factory=dict, description="Dataset info")
    configuration_info: Dict[str, Any] = Field(default_factory=dict, description="Config info")
    quality_metrics: QualityMetrics = Field(..., description="Quality metrics summary")
    performance_metrics: PerformanceMetrics = Field(..., description="Performance metrics summary")
    reliability_metrics: ReliabilityMetrics = Field(..., description="Reliability metrics summary")
    multilingual_breakdown: Dict[str, QualityMetrics] = Field(default_factory=dict, description="Quality by language")
    agricultural_breakdown: Dict[str, QualityMetrics] = Field(default_factory=dict, description="Quality by domain category")
    baseline_comparisons: List[BaselineResult] = Field(default_factory=list, description="Baseline comparison results")
    regression_comparisons: List[RegressionResult] = Field(default_factory=list, description="Regression comparison results")
    failure_summary: Dict[str, Any] = Field(default_factory=dict, description="Summary of failed/edge cases")
    traceability_samples: List[Dict[str, Any]] = Field(default_factory=list, description="Sample case traces")
    limitations: List[str] = Field(default_factory=list, description="Known evaluation limitations")
    not_evaluable_fields: List[str] = Field(default_factory=list, description="Fields marked NOT_EVALUABLE or INSUFFICIENT_DATA")
