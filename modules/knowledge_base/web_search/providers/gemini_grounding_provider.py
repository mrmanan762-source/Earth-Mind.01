"""Gemini Grounding with Google Search Provider Adapter for EarthMind Stage R10 Web Search.

Role: Secondary Managed Search / Grounded Research Provider.
Official documentation: https://ai.google.dev/gemini-api/docs/google-search

PREPARATION CONTRACT:
- Implements IWebSearchProvider.
- Follows the existing WebSearchProvider contract.
- Supports secure configuration for its API key via EARTHMIND_WEB_SEARCH_GEMINI_API_KEY.
- is_available() returns False when credentials are not configured.
- Output handling is designed specifically for Gemini Grounding responses:
  - Grounded text response & candidate content.
  - Web search queries generated by Gemini.
  - Grounding chunks (web source URIs and titles).
  - Grounding supports (text segment spans, source indices, confidence scores).
- Normalizes grounding chunks into WebSearchResult with result_type='grounded_search'
  preserving citations, source URLs, and grounding metadata.
- Never makes a live network request until credentials are configured.
"""

import json
import logging
import time
import urllib.error
import urllib.parse
import urllib.request
from typing import Any, Dict, List, Optional

from core.config.settings import WebSearchConfig
from core.errors.exceptions import (
    InvalidWebSearchRequestError,
    WebSearchAuthenticationError,
    WebSearchExecutionError,
    WebSearchProviderUnavailableError,
    WebSearchRateLimitError,
    WebSearchTimeoutError,
)
from core.interfaces.web_search import IWebSearchProvider
from core.schemas.web_search import (
    WebSearchRequest,
    WebSearchResponse,
    WebSearchResult,
    WebSearchStatus,
)

logger = logging.getLogger(__name__)


class GeminiGroundingSearchProvider(IWebSearchProvider):
    """Gemini API adapter with Google Search Grounding tool enabled."""

    def __init__(
        self,
        config: Optional[WebSearchConfig] = None,
        api_key: Optional[str] = None,
        endpoint: Optional[str] = None,
        timeout: Optional[float] = None,
        user_agent: Optional[str] = None,
    ):
        cfg = config or WebSearchConfig()
        self._api_key = api_key or cfg.gemini_api_key
        self._endpoint = endpoint or cfg.gemini_endpoint
        self._timeout = timeout if timeout is not None else cfg.timeout
        self._user_agent = user_agent or cfg.user_agent

    @property
    def provider_name(self) -> str:
        return "gemini_grounding"

    def is_available(self) -> bool:
        """Returns True only when valid API key credentials are configured."""
        return bool(self._endpoint and self._endpoint.strip() and self._api_key and self._api_key.strip())

    def supported_capabilities(self) -> Dict[str, Any]:
        return {
            "grounded_search": True,
            "google_search_grounding": True,
            "grounding_citations": True,
            "multilingual_queries": True,
            "max_results_limit": 10,
            "requires_credentials": True,
            "credentials_present": self.is_available(),
        }

    def search(self, request: WebSearchRequest) -> WebSearchResponse:
        """Executes Gemini Grounding search query if credentials configured, else raises WebSearchAuthenticationError."""
        start_time = time.perf_counter()

        if not request.query_text or not request.query_text.strip():
            raise InvalidWebSearchRequestError("Search query text cannot be empty.")

        if not self._api_key or not self._api_key.strip():
            raise WebSearchAuthenticationError(
                self.provider_name,
                "Gemini API key is not configured. Set EARTHMIND_WEB_SEARCH_GEMINI_API_KEY when credentials are available."
            )

        timeout = request.timeout if request.timeout > 0 else self._timeout

        # Build Gemini request payload with Google Search tool enabled
        payload: Dict[str, Any] = {
            "contents": [
                {
                    "parts": [
                        {
                            "text": (
                                f"Provide factual agricultural information and verified references for: {request.query_text}"
                            )
                        }
                    ]
                }
            ],
            "tools": [
                {
                    "google_search": {}
                }
            ],
        }

        req_data = json.dumps(payload).encode("utf-8")
        url = self._endpoint
        req = urllib.request.Request(
            url,
            data=req_data,
            headers={
                "User-Agent": self._user_agent,
                "Content-Type": "application/json",
                "Accept": "application/json",
                "x-goog-api-key": self._api_key,
            },
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=timeout) as response:
                status_code = response.getcode()
                raw_body = response.read().decode("utf-8")
                data = json.loads(raw_body)
        except urllib.error.HTTPError as http_err:
            if http_err.code in (401, 403):
                raise WebSearchAuthenticationError(
                    self.provider_name, f"HTTP {http_err.code}: Invalid Gemini API key or unauthorized access."
                )
            elif http_err.code == 429:
                raise WebSearchRateLimitError(
                    self.provider_name, f"HTTP {http_err.code}: Gemini API quota/rate limit exceeded."
                )
            elif http_err.code in (500, 502, 503, 504):
                raise WebSearchProviderUnavailableError(
                    self.provider_name, f"HTTP {http_err.code}: Gemini service unavailable."
                )
            else:
                raise WebSearchExecutionError(
                    self.provider_name, f"HTTP {http_err.code}: Gemini grounding request failed: {http_err.reason}"
                )
        except TimeoutError:
            raise WebSearchTimeoutError(self.provider_name, timeout)
        except urllib.error.URLError as url_err:
            if isinstance(url_err.reason, TimeoutError) or "timed out" in str(url_err.reason).lower():
                raise WebSearchTimeoutError(self.provider_name, timeout)
            raise WebSearchProviderUnavailableError(
                self.provider_name, f"Network error connecting to Gemini: {url_err.reason}"
            )
        except json.JSONDecodeError as json_err:
            raise WebSearchExecutionError(
                self.provider_name, f"Failed to parse Gemini response: {json_err}"
            )

        candidates = data.get("candidates", [])
        if not candidates:
            elapsed_ms = (time.perf_counter() - start_time) * 1000.0
            return WebSearchResponse(
                request_id=request.request_id,
                status=WebSearchStatus.EMPTY_RESULT,
                query_text=request.query_text,
                results=[],
                result_count=0,
                provider_name=self.provider_name,
                execution_time_ms=elapsed_ms,
            )

        first_cand = candidates[0]
        grounded_body = ""
        parts = first_cand.get("content", {}).get("parts", [])
        for p in parts:
            if "text" in p:
                grounded_body += p["text"] + "\n"
        grounded_body = grounded_body.strip()

        grounding_meta = first_cand.get("grounding_metadata", {})
        grounding_chunks = grounding_meta.get("grounding_chunks", [])
        web_queries = grounding_meta.get("web_search_queries", [])
        grounding_supports = grounding_meta.get("grounding_supports", [])

        now_ts = time.time()
        results: List[WebSearchResult] = []

        if grounding_chunks:
            for idx, chunk in enumerate(grounding_chunks, start=1):
                web_info = chunk.get("web", {})
                uri = web_info.get("uri") or ""
                title = web_info.get("title") or "Google Grounded Source"
                domain = urllib.parse.urlparse(uri).netloc if uri else None

                chunk_index = idx - 1
                associated_supports = [
                    sup.get("segment", {}).get("text", "")
                    for sup in grounding_supports
                    if chunk_index in sup.get("grounding_chunk_indices", [])
                ]
                snippet = " ".join(associated_supports).strip() if associated_supports else grounded_body[:300]

                res_id = f"gemini_ground_{idx}_{hash(uri or title) & 0xffff}"
                results.append(
                    WebSearchResult(
                        result_id=res_id,
                        title=title,
                        url=uri,
                        canonical_url=uri,
                        result_type="grounded_search",
                        snippet=snippet or title,
                        source=domain or "Google Search",
                        provider=self.provider_name,
                        retrieval_timestamp=now_ts,
                        rank=idx,
                        provenance={
                            "provider": self.provider_name,
                            "query": request.query_text,
                            "retrieval_timestamp": now_ts,
                        },
                        metadata={
                            "grounded_response_summary": grounded_body[:500] if grounded_body else None,
                            "web_search_queries": web_queries,
                            "chunk_index": chunk_index,
                        },
                        request_id=request.request_id,
                    )
                )
        elif grounded_body:
            res_id = f"gemini_ground_synth_{hash(grounded_body) & 0xffff}"
            results.append(
                WebSearchResult(
                    result_id=res_id,
                    title="Gemini Grounded Research Summary",
                    url="https://google.com/search",
                    canonical_url="https://google.com/search",
                    result_type="grounded_search",
                    snippet=grounded_body[:600],
                    source="google.com",
                    provider=self.provider_name,
                    retrieval_timestamp=now_ts,
                    rank=1,
                    provenance={
                        "provider": self.provider_name,
                        "query": request.query_text,
                        "retrieval_timestamp": now_ts,
                    },
                    metadata={
                        "web_search_queries": web_queries,
                        "has_structured_chunks": False,
                    },
                    request_id=request.request_id,
                )
            )

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0

        return WebSearchResponse(
            request_id=request.request_id,
            status=WebSearchStatus.SUCCESS if results else WebSearchStatus.EMPTY_RESULT,
            query_text=request.query_text,
            results=results,
            result_count=len(results),
            provider_name=self.provider_name,
            execution_time_ms=elapsed_ms,
            trace_info={
                "provider": self.provider_name,
                "web_search_queries": web_queries,
                "grounding_chunk_count": len(grounding_chunks),
            },
        )
