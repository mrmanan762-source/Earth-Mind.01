import uuid
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from modules.reasoning.schemas import (
    ReasoningFinding,
    ReasoningResult,
    ReasoningValidationHandoff,
)


class TraceRecord(BaseModel):
    """Structured audit trace record connecting request_id, evidence, operations, findings, and handoffs."""
    trace_id: str = Field(..., description="Unique trace identifier")
    request_id: str = Field(..., description="Request ID being traced")
    operation: str = Field(..., description="Reasoning operation or step name")
    evidence_ids: List[str] = Field(default_factory=list, description="Evidence IDs involved in operation")
    finding_ids: List[str] = Field(default_factory=list, description="Finding IDs generated by operation")
    iteration_index: int = Field(1, ge=1, description="Iteration index of operation")
    timestamp: str = Field(..., description="ISO string timestamp")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary operation metadata")


class ReasoningTraceManager:
    """Manages structured audit traces and links request -> evidence -> operation -> finding -> validation handoff.

    Note: Traceability means structured operation/evidence references, NOT private internal chain-of-thought text.
    """

    def __init__(self):
        self._traces: Dict[str, List[TraceRecord]] = {}

    def record_operation(
        self,
        request_id: str,
        operation: str,
        evidence_ids: Optional[List[str]] = None,
        finding_ids: Optional[List[str]] = None,
        iteration_index: int = 1,
        timestamp: str = "",
        metadata: Optional[Dict[str, Any]] = None
    ) -> TraceRecord:
        """Record a structured operation step into the trace log."""
        import datetime
        trace_id = f"trace_{request_id}_{uuid.uuid4().hex[:8]}"
        ts = timestamp or datetime.datetime.now(datetime.timezone.utc).isoformat()

        record = TraceRecord(
            trace_id=trace_id,
            request_id=request_id,
            operation=operation,
            evidence_ids=evidence_ids or [],
            finding_ids=finding_ids or [],
            iteration_index=iteration_index,
            timestamp=ts,
            metadata=metadata or {}
        )

        if request_id not in self._traces:
            self._traces[request_id] = []
        self._traces[request_id].append(record)
        return record

    def build_trace_summary(
        self,
        result: ReasoningResult,
        handoff: Optional[ReasoningValidationHandoff] = None
    ) -> Dict[str, Any]:
        """Build structured traceability summary linking request -> evidence -> findings -> handoff."""
        req_id = result.request_id
        records = self._traces.get(req_id, [])

        finding_ids = [f.finding_id for f in result.findings]
        evidence_ids = result.evidence_references
        conflict_ids = [c.conflict_id for c in result.conflicts]
        uncertainty_ids = [u.uncertainty_id for u in result.uncertainty]

        return {
            "request_id": req_id,
            "trace_id": result.trace_id,
            "status": result.status.value,
            "evidence_count": len(evidence_ids),
            "evidence_ids": evidence_ids,
            "finding_count": len(finding_ids),
            "finding_ids": finding_ids,
            "conflict_count": len(conflict_ids),
            "conflict_ids": conflict_ids,
            "uncertainty_count": len(uncertainty_ids),
            "uncertainty_ids": uncertainty_ids,
            "recorded_operations": [r.model_dump() for r in records],
            "validation_handoff_id": handoff.handoff_id if handoff else None,
            "validation_status": handoff.validation_status.value if handoff else None,
        }
